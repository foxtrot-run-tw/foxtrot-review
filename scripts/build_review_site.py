#!/usr/bin/env python3
"""Generate static Fox Trot review-site pages from data/days.js.

Content is readable without JavaScript. Bump ASSET_VERSION on every deploy
so CSS and JS cache-busting query strings change.
"""

from __future__ import annotations

import json
import html
import re
from collections import OrderedDict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSET_VERSION = "20261112c"

WEEKDAYS = "一二三四五六日"
# datetime weekday: Mon=0 ... Sun=6; we want 日一二三四五六
WEEKDAY_ZH = ["一", "二", "三", "四", "五", "六", "日"]

TYPE_META = {
    "daily-6": {"label": "每日六平台", "slug": "daily"},
    "ig-carousel": {"label": "IG 輪播", "slug": "ig-carousel"},
}
TYPE_ORDER = ["daily-6", "ig-carousel"]
TYPE_SORT = {"ig-carousel": 0, "daily-6": 1}
PLATFORM_ORDER = ["x", "threads", "instagram", "facebook", "linkedin", "web"]
PLATFORM_LABEL = {
    "x": "X",
    "threads": "Threads",
    "instagram": "Instagram",
    "facebook": "Facebook",
    "linkedin": "LinkedIn",
    "web": "網頁文章",
}


def esc(value) -> str:
    return html.escape("" if value is None else str(value), quote=True)


def load_days() -> list:
    text = (ROOT / "data" / "days.js").read_text(encoding="utf-8")
    start = text.index("[", text.index("window.FOX_TROT_DAYS"))
    end = text.rindex("]")
    days = json.loads(text[start : end + 1])
    return sort_days(days)


def entry_type(day: dict) -> str:
    return day.get("type") or "daily-6"


def type_label(typ: str) -> str:
    meta = TYPE_META.get(typ)
    return meta["label"] if meta else typ


def slug_of(day: dict) -> str:
    typ = entry_type(day)
    suffix = TYPE_META.get(typ, {}).get("slug", typ)
    if typ == "daily-6":
        return f"{day['date']}-daily"
    if day.get("id"):
        return day["id"]
    return f"{day['date']}-{suffix}"


def post_filename(day: dict) -> str:
    return f"{slug_of(day)}.html"


def sort_days(days: list) -> list:
    def key(day):
        typ = entry_type(day)
        return (day["date"], -TYPE_SORT.get(typ, 9))

    # newest date first, then carousel before daily-6
    return sorted(days, key=key, reverse=True)


def format_date(iso: str) -> str:
    y, m, d = [int(p) for p in iso.split("-")]
    wd = WEEKDAY_ZH[date(y, m, d).weekday()]
    return f"{y}年{m}月{d}日（{wd}）"


def asset(rel: str, src: str) -> str:
    if not src:
        return ""
    if re.match(r"^(https?:)?//", src) or src.startswith("data:"):
        return src
    return rel + src


def load_fragment(name: str) -> str:
    return (ROOT / "data" / "content" / name).read_text(encoding="utf-8").strip()


def nav_html(rel: str, current: str) -> str:
    items = [
        ("index.html", "home", "首頁"),
        ("quality.html", "quality", "品質把關原則"),
        ("workflow.html", "workflow", "工作流程"),
    ]
    links = []
    for href, key, label in items:
        current_attr = ' aria-current="page"' if key == current else ""
        links.append(f'<a href="{esc(rel + href)}"{current_attr}>{esc(label)}</a>')
    return '<nav class="site-nav" aria-label="主要">' + "".join(links) + "</nav>"


