def image_of(day: dict, key: str):
    images = day.get("images") or {}
    return images.get(key)


def thumb_src(day: dict) -> str:
    typ = entry_type(day)
    if typ == "ig-carousel":
        slides = day.get("slides") or []
        return slides[0]["src"] if slides else ""
    img = image_of(day, "ig") or image_of(day, "square") or image_of(day, "wide")
    return img["src"] if img else ""


def thumb_alt(day: dict) -> str:
    typ = entry_type(day)
    if typ == "ig-carousel":
        slides = day.get("slides") or []
        return (slides[0].get("alt") if slides else "") or (day.get("topic") or "")
    img = image_of(day, "ig") or image_of(day, "square")
    return (img.get("alt") if img else "") or (day.get("topic") or day.get("title") or "")


def title_of(day: dict) -> str:
    return day.get("topic") or day.get("title") or slug_of(day)


def render_sources(day: dict) -> str:
    sources = day.get("sources") or []
    if not sources:
        return ""
    items = []
    for source in sources:
        if source.get("url"):
            title = f'<a href="{esc(source["url"])}" target="_blank" rel="noopener noreferrer">{esc(source.get("title") or source["url"])}</a>'
        else:
            title = f'<strong>{esc(source.get("title") or "")}</strong>'
        meta = " · ".join(p for p in [source.get("authors"), source.get("outlet")] if p)
        meta_html = f'<p class="source-meta">{esc(meta)}</p>' if meta else ""
        note_html = f'<p class="source-note">{esc(source.get("note"))}</p>' if source.get("note") else ""
        items.append(f"<li>{title}{meta_html}{note_html}</li>")
    return (
        '<section class="panel" id="sources">\n'
        "<h3>資料來源</h3>\n"
        f'<ul class="source-list">{"".join(items)}</ul>\n'
        "</section>"
    )


RESULT_LABEL = {"pass": "通過", "fail": "未通過", "na": "不適用"}


def render_checks(day: dict) -> str:
    checks = day.get("selfCheck") or []
    if not checks:
        return ""
    items = []
    for check in checks:
        result = check.get("result") or ""
        label = RESULT_LABEL.get(result, result)
        note = f'<p class="check-note">{esc(check.get("note"))}</p>' if check.get("note") else ""
        items.append(
            "<li>"
            f'<div class="check-head"><span class="check-item">{esc(check.get("item"))}</span>'
            f'<span class="pill pill-{esc(result)}">{esc(label)}</span></div>'
            f"{note}"
            "</li>"
        )
    return (
        '<section class="panel" id="self-check">\n'
        "<h3>品質自我檢查</h3>\n"
        f'<ul class="check-list">{"".join(items)}</ul>\n'
        "</section>"
    )


def copy_block(copy_id: str, text: str, label: str = "複製文字") -> str:
    if not text:
        return ""
    return (
        f'<button type="button" class="btn btn-primary js-copy" data-copy-for="{esc(copy_id)}">{esc(label)}</button>'
        f'<textarea id="{esc(copy_id)}" class="visually-hidden" readonly>{esc(text)}</textarea>'
    )


def download_link(rel: str, image: dict, label: str = "下載圖片") -> str:
    if not image or not image.get("src"):
        return ""
    name = image.get("filename") or Path(image["src"]).name
    alt = image.get("alt") or name
    return (
        f'<a class="btn" href="{esc(asset(rel, image["src"]))}" download="{esc(name)}" '
        f'aria-label="{esc(label + "：" + alt)}">{esc(label)}</a>'
    )


def toolbar(label: str, actions: str) -> str:
    return (
        '<div class="card-toolbar">'
        f'<div class="platform-name">{esc(label)}</div>'
        f'<div class="toolbar-actions">{actions}</div>'
        "</div>"
    )


def user_row(rel: str, day: dict, name: str, meta: str, extra: str = "") -> str:
    info = image_of(day, "avatar")
    src = asset(rel, info["src"]) if info else ""
    alt = info.get("alt") if info else "Fox Trot"
    extra_html = extra or ""
    meta_html = f'<p class="user-meta">{esc(meta)}</p>' if meta else ""
    return (
        '<div class="post-user">'
        f'<img class="avatar" src="{esc(src)}" alt="{esc(alt)}">'
        f"<div><p class=\"user-name\">{name}</p>{meta_html}</div>"
        f"{extra_html}"
        "</div>"
    )


def post_image(rel: str, image: dict, ratio: str) -> str:
    if not image:
        return ""
    return (
        f'<div class="post-image-wrap {esc(ratio)}">'
        f'<img src="{esc(asset(rel, image["src"]))}" alt="{esc(image.get("alt") or "")}">'
        "</div>"
    )


def render_platform(rel: str, day: dict, key: str) -> str:
    post = (day.get("posts") or {}).get(key)
    if not post:
        return ""
    image = image_of(day, post.get("imageKey") or "")
    actions = copy_block(f"copy-{slug_of(day)}-{key}", post.get("copyText") or "")
    if image:
        actions += download_link(rel, image)
    label = PLATFORM_LABEL.get(key, key)
    wrap_class = {
        "web": "card-wrap span-2",
        "threads": "card-wrap threads",
        "instagram": "card-wrap ig",
        "facebook": "card-wrap fb",
        "linkedin": "card-wrap li",
        "x": "card-wrap x",
    }.get(key, "card-wrap")

    if key == "web":
        hero = ""
        if image:
            hero = (
                '<div class="article-hero">'
                f'<img src="{esc(asset(rel, image["src"]))}" alt="{esc(image.get("alt") or "")}">'
                "</div>"
            )
        sections_html = []
        for section in post.get("sections") or []:
            typ = section.get("type")
            if typ == "h":
                sections_html.append(f"<h3>{esc(section.get('text'))}</h3>")
            elif typ == "p":
                sections_html.append(f"<p>{esc(section.get('text'))}</p>")
            elif typ == "ol":
                lis = "".join(f"<li>{esc(item)}</li>" for item in section.get("items") or [])
                sections_html.append(f"<ol>{lis}</ol>")
        counts = day.get("charCounts") or {}
        count_html = ""
        if counts:
            count_html = (
                f'<p class="article-count">正文約 {esc(counts.get("webCjk"))} 個中文字'
                f'（含標點與英文數字約 {esc(counts.get("webNoWhitespace"))} 字元，不含空白）。</p>'
            )
        dek = f'<p class="article-dek">{esc(post.get("dek"))}</p>' if post.get("dek") else ""
        body = (
            '<article class="post article">'
            f"{hero}"
            '<div class="article-body">'
            '<p class="article-kicker">Fox Trot 專欄</p>'
            f'<h2 class="article-title">{esc(post.get("title") or title_of(day))}</h2>'
            f"{dek}"
            f'<p class="article-byline">Fox Trot 編輯部 · {esc(format_date(day["date"]))} · 審查用，未發布</p>'
            f'{"".join(sections_html)}{count_html}'
            "</div></article>"
        )
        return f'<div class="{wrap_class}">{toolbar(label, actions)}{body}</div>'

    if key == "threads":
        inner = (
            user_row(rel, day, esc(post.get("displayName") or "Fox Trot"), f"@{post.get('handle') or 'foxtrot'} · 審查用")
            + f'<div class="post-text">{esc(post.get("text"))}</div>'
            + post_image(rel, image, "ratio-1x1")
        )
    elif key == "instagram":
        tags = ""
        if post.get("hashtags"):
            tags = "\n\n" + " ".join(post["hashtags"])
        caption = (
            '<div class="ig-caption">'
            f'<span class="ig-name">{esc(post.get("displayName") or "Fox Trot")}</span> '
            f'{esc(post.get("caption") or "")}'
            f'<span class="ig-tags">{esc(tags)}</span>'
            "</div>"
        )
        inner = (
            user_row(rel, day, esc(post.get("displayName") or "Fox Trot"), "審查用，未發布")
            + post_image(rel, image, "ratio-4x5")
            + '<div class="icon-row"><span>♡  讚</span><span>💬  留言</span><span>↗  分享</span></div>'
            + caption
        )
    elif key == "facebook":
        inner = (
            user_row(rel, day, esc(post.get("displayName") or "Fox Trot"), f"{format_date(day['date'])} · 審查用")
            + f'<div class="post-text">{esc(post.get("text"))}</div>'
            + post_image(rel, image, "ratio-16x9")
            + '<div class="icon-row"><span>讚</span><span>留言</span><span>分享</span></div>'
        )
    elif key == "linkedin":
        follow = '<span class="li-follow">關注</span>'
        inner = (
            user_row(
                rel,
                day,
                esc(post.get("displayName") or "Fox Trot"),
                f"{post.get('subtitle') or '虛構跑步品牌'} · 審查用",
                follow,
            )
            + f'<div class="post-text">{esc(post.get("text"))}</div>'
            + post_image(rel, image, "ratio-16x9")
            + '<div class="icon-row"><span>推薦</span><span>留言</span><span>轉發</span></div>'
        )
    elif key == "x":
        name = (
            f'{esc(post.get("displayName") or "Fox Trot")} '
            f'<span class="x-handle">@{esc(post.get("handle") or "FoxTrot")}</span>'
        )
        info = image_of(day, "avatar")
        src = asset(rel, info["src"]) if info else ""
        alt = info.get("alt") if info else "Fox Trot"
        inner = (
            '<div class="post-user">'
            f'<img class="avatar" src="{esc(src)}" alt="{esc(alt)}">'
            f'<div><p class="user-name">{name}</p>'
            f'<p class="user-meta">{esc(format_date(day["date"]))} · 審查用</p></div>'
            "</div>"
            f'<div class="post-text">{esc(post.get("text"))}</div>'
            + post_image(rel, image, "ratio-1x1")
            + '<div class="icon-row"><span>回覆</span><span>轉發</span><span>喜歡</span></div>'
        )
    else:
        return ""

    return f'<div class="{wrap_class}">{toolbar(label, actions)}<div class="post">{inner}</div></div>'


def render_day_head(day: dict) -> str:
    typ = entry_type(day)
    badges = (
        f'<span class="badge badge-type">{esc(type_label(typ))}</span>'
        + (
            f'<span class="badge">{esc(day.get("cycle"))} 日 · {esc(day.get("cycleLabel") or "")}</span>'
            if day.get("cycle")
            else ""
        )
        + f'<span class="badge badge-date">{esc(format_date(day["date"]))}</span>'
    )
    summary = f'<p class="day-summary">{esc(day.get("summary"))}</p>' if day.get("summary") else ""
    return (
        '<header class="day-head">'
        f'<div><p class="day-kicker">{badges}</p>'
        f'<h1 class="day-title">{esc(title_of(day))}</h1></div>'
        f"{summary}"
        "</header>"
    )


def render_pager(day: dict, days: list, rel_posts_are_local: bool) -> str:
    # Post pages live in posts/, so sibling links have no prefix; home is ../index.html
    index = next(i for i, d in enumerate(days) if slug_of(d) == slug_of(day))
    newer = days[index - 1] if index > 0 else None
    older = days[index + 1] if index + 1 < len(days) else None

    def link(target, label_prefix):
        href = post_filename(target)
        return f'<a href="{esc(href)}">{esc(label_prefix)}：{title_of(target)}</a>'

    items = []
    if newer:
        items.append(f"<li>{link(newer, '較新')}</li>")
    items.append('<li><a class="pager-home" href="../index.html#directory">回到目錄</a></li>')
    if older:
        items.append(f"<li>{link(older, '較舊')}</li>")
    return '<nav aria-label="前後則貼文"><ul class="post-pager">' + "".join(items) + "</ul></nav>"


def render_carousel(rel: str, day: dict) -> str:
    slides = day.get("slides") or []
    actions = copy_block(f"copy-{slug_of(day)}", day.get("copyText") or "", "複製文案")
    if day.get("zip"):
        actions += download_link(rel, day["zip"], "打包下載")

    slide_figs = []
    dots = []
    stack_items = []
    for i, slide in enumerate(slides, 1):
        src = asset(rel, slide["src"])
        alt = slide.get("alt") or f"第 {i} 張"
        fname = slide.get("filename") or Path(slide["src"]).name
        slide_figs.append(
            f'<figure class="carousel-slide" id="{esc(slug_of(day))}-slide-{i}">'
            f'<img src="{esc(src)}" alt="{esc(alt)}" draggable="false">'
            "</figure>"
        )
        selected = "true" if i == 1 else "false"
        active = " is-active" if i == 1 else ""
        dots.append(
            f'<button type="button" class="carousel-dot{active}" role="tab" '
            f'aria-label="第 {i} 張" aria-selected="{selected}"></button>'
        )
        stack_items.append(
            "<li>"
            f'<img class="slide-list-thumb" src="{esc(src)}" alt="">'
            "<div>"
            f'<div class="slide-download-label">第 {i} 張</div>'
            f'<p class="slide-alt">{esc(alt)}</p>'
            + download_link(rel, slide, f"下載第 {i} 張")
            + "</div></li>"
        )

    tags = ""
    if day.get("hashtags"):
        tags = "\n\n" + " ".join(day["hashtags"])
    caption = (
        '<div class="ig-caption">'
        f'<span class="ig-name">{esc(day.get("displayName") or "Fox Trot")}</span> '
        f'{esc(day.get("caption") or "")}'
        f'<span class="ig-tags">{esc(tags)}</span>'
        "</div>"
    )

    preview = (
        '<div class="card-wrap ig carousel-preview" data-carousel="true">'
        + toolbar("Instagram 輪播", actions)
        + '<div class="post">'
        + user_row(rel, day, esc(day.get("displayName") or "Fox Trot"), "審查用，未發布 · 輪播")
        + '<div class="carousel-frame">'
        + '<div class="carousel-scroller" tabindex="0" role="region" aria-roledescription="carousel" '
        + f'aria-label="{esc(title_of(day))}，可用左右鍵或滑動切換">'
        + "".join(slide_figs)
        + "</div>"
        + '<button type="button" class="carousel-nav carousel-prev" aria-label="上一張">‹</button>'
        + '<button type="button" class="carousel-nav carousel-next" aria-label="下一張">›</button>'
        + f'<div class="carousel-counter">1 / {len(slides)}</div>'
        + '<div class="visually-hidden carousel-live" aria-live="polite"></div>'
        + "</div>"
        + '<div class="carousel-dots" role="tablist" aria-label="選擇張數">'
        + "".join(dots)
        + "</div>"
        + '<div class="icon-row"><span>♡  讚</span><span>💬  留言</span><span>↗  分享</span></div>'
        + caption
        + "</div></div>"
    )

    all_actions = ""
    if day.get("zip"):
        all_actions += download_link(rel, day["zip"], "打包下載全部（ZIP）")
    if day.get("contactSheet"):
        all_actions += download_link(rel, day["contactSheet"], "下載總覽圖")
    sheet = ""
    if day.get("contactSheet"):
        cs = day["contactSheet"]
        sheet = (
            f'<a class="contact-sheet-link" href="{esc(asset(rel, cs["src"]))}" '
            f'download="{esc(cs.get("filename") or "contact-sheet.jpg")}">'
            f'<img src="{esc(asset(rel, cs["src"]))}" alt="{esc(cs.get("alt") or "輪播總覽")}">'
            "</a>"
        )

    meta = (
        '<div class="carousel-meta">'
        '<section class="panel carousel-side-panel">'
        "<h3>下載與替代文字</h3>"
        f'<div class="toolbar-actions carousel-all-actions">{all_actions}</div>'
        f"{sheet}"
        f'<ol class="slide-download-list">{"".join(stack_items)}</ol>'
        "</section></div>"
    )
    return f'<div class="carousel-layout">{preview}{meta}</div>'


def render_post_page(day: dict, days: list) -> str:
    rel = "../"
    typ = entry_type(day)
    head = render_day_head(day)
    pager = render_pager(day, days, True)
    if typ == "ig-carousel":
        body = render_carousel(rel, day)
    else:
        cards = "".join(render_platform(rel, day, key) for key in PLATFORM_ORDER)
        body = f'<div class="cards">{cards}</div>'
    main = head + pager + body + render_sources(day) + render_checks(day)
    desc = f"Fox Trot 審查頁：{title_of(day)}。所有內容均未發布至任何社群平台。"
    return shell(
        title=f"{title_of(day)} · Fox Trot 審查頁",
        description=desc,
        body_class=f"page-post page-{typ}",
        current_nav="",
        rel=rel,
        main=main,
    )


def render_directory(days: list) -> str:
    rel = ""
    types_present = []
    for typ in TYPE_ORDER:
        if any(entry_type(d) == typ for d in days):
            types_present.append(typ)
    for d in days:
        typ = entry_type(d)
        if typ not in types_present:
            types_present.append(typ)

    tabs = ['<button type="button" class="type-tab is-active" role="tab" data-type="all" aria-selected="true">全部</button>']
    for typ in types_present:
        tabs.append(
            f'<button type="button" class="type-tab" role="tab" data-type="{esc(typ)}" aria-selected="false">{esc(type_label(typ))}</button>'
        )

    groups = OrderedDict()
    for day in days:
        groups.setdefault(day["date"], []).append(day)

    groups_html = []
    for iso, items in groups.items():
        cards = []
        for day in items:
            typ = entry_type(day)
            href = "posts/" + post_filename(day)
            src = asset(rel, thumb_src(day))
            summary = day.get("summary") or ""
            topic_badge = ""
            if day.get("cycle"):
                topic_badge = f'<span class="badge">{esc(day.get("cycle"))} 日 · {esc(day.get("cycleLabel") or "")}</span>'
            cards.append(
                f'<article class="dir-item" data-type="{esc(typ)}" data-date="{esc(iso)}" data-slug="{esc(slug_of(day))}">'
                f'<a href="{esc(href)}">'
                f'<img class="dir-thumb" src="{esc(src)}" alt="{esc(thumb_alt(day))}">'
                "<div>"
                '<p class="dir-meta">'
                f'<span class="badge badge-type">{esc(type_label(typ))}</span>'
                f"{topic_badge}"
                f'<span class="badge badge-date">{esc(format_date(iso))}</span>'
                "</p>"
                f"<h3>{esc(title_of(day))}</h3>"
                f'<p class="dir-summary">{esc(summary)}</p>'
                "</div></a></article>"
            )
        groups_html.append(
            f'<section class="dir-group" data-date="{esc(iso)}">'
            f'<h3 class="dir-group-title">{esc(format_date(iso))}</h3>'
            f'<div class="dir-list">{"".join(cards)}</div>'
            "</section>"
        )

    index_json = json.dumps(
        [
            {
                "date": day["date"],
                "type": entry_type(day),
                "slug": slug_of(day),
                "href": "posts/" + post_filename(day),
                "title": title_of(day),
            }
            for day in days
        ],
        ensure_ascii=False,
    )

    return (
        '<section class="section-block" id="directory">\n'
        "<h2>貼文目錄</h2>\n"
        '<p>依日期由新到舊排列。點進去可看完整文案、圖片、資料來源與該則自我檢查。此目錄不必開 JavaScript 就能瀏覽；版型篩選是額外功能。</p>\n'
        '<div class="directory-toolbar">'
        f'<div id="type-filter" class="type-filter" role="tablist" aria-label="依版型篩選">{"".join(tabs)}</div>'
        "</div>\n"
        '<p class="dir-empty">這個篩選目前沒有貼文。</p>\n'
        f'{"".join(groups_html)}\n'
        f'<script type="application/json" id="post-index">{index_json}</script>\n'
        "</section>"
    )


def render_sitemap(days: list) -> str:
    links = [
        ("index.html", "首頁", "品牌策略、主題規劃與貼文目錄"),
        ("quality.html", "品質把關原則", "五項檢查、圖文規則與工作邊界"),
        ("workflow.html", "工作流程", "製作步驟、工具、時間與改版紀錄"),
    ]
    items = [
        f'<li><a href="{esc(href)}">{esc(label)}</a><span>{esc(note)}</span></li>'
        for href, label, note in links
    ]
    for day in days:
        href = "posts/" + post_filename(day)
        note = f'{format_date(day["date"])} · {type_label(entry_type(day))}'
        items.append(f'<li><a href="{esc(href)}">{esc(title_of(day))}</a><span>{esc(note)}</span></li>')
    return (
        '<section class="section-block" id="sitemap">\n'
        "<h2>本站頁面</h2>\n"
        "<p>下面是目前審查站上的全部頁面，方便直接開啟或交給外部工具抓取。</p>\n"
        f'<ul class="sitemap-list">{"".join(items)}</ul>\n'
        "</section>"
    )


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


